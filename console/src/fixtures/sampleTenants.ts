// Synthetic baseline findings only; no production customer measurements.
export function remediationPercent(tenant: SampleTenant): number | null {
  if (tenant.misconfigsBaseline <= 0 || tenant.misconfigsCurrent < 0 || tenant.misconfigsCurrent > tenant.misconfigsBaseline) return null
  return Math.round(((tenant.misconfigsBaseline - tenant.misconfigsCurrent) / tenant.misconfigsBaseline) * 100)
}
